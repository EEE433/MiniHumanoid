"""Export a trained PPO walking policy as a compact ESP32 C++ motion table.

From the repository root:
  python RL/export_walk.py --run RL/runs/walk --output ESP32Humanoid/include/generated_walk.h
"""
import argparse
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", default=os.path.join(HERE, "runs", "walk"),
                        help="directory containing final_model.zip and vecnormalize.pkl")
    parser.add_argument("--model", default="final_model.zip", help="PPO model filename inside --run")
    parser.add_argument("--output", default=os.path.join(HERE, "..", "ESP32Humanoid", "include", "generated_walk.h"))
    parser.add_argument("--seconds", type=float, default=3.0, help="simulation duration to export")
    parser.add_argument("--stride", type=int, default=3, help="keep every Nth 20 ms control sample; default 60 ms")
    parser.add_argument("--max-angle-deg", type=float, default=20.0,
                        help="safety clamp for target offsets from the simulated home pose")
    parser.add_argument("--vx", type=float, default=0.08, help="forward command in m/s")
    parser.add_argument("--vy", type=float, default=0.0, help="left command in m/s")
    parser.add_argument("--wz", type=float, default=0.0, help="counter-clockwise command in rad/s")
    parser.add_argument("--seed", type=int, default=1234)
    args = parser.parse_args()

    if args.seconds <= 0 or args.stride < 1 or args.max_angle_deg <= 0:
        parser.error("seconds, stride and max-angle-deg must be positive")
    args.run = os.path.abspath(args.run)
    args.output = os.path.abspath(args.output)

    try:
        from stable_baselines3 import PPO
        from stable_baselines3.common.vec_env import DummyVecEnv, VecNormalize
        from walk_env import WalkEnv
    except ImportError as exc:
        raise SystemExit(f"Missing RL dependencies; install RL/requirements.txt. {exc}")

    model_path = os.path.join(args.run, args.model)
    stats_path = os.path.join(args.run, "vecnormalize.pkl")
    if not os.path.isfile(model_path) or not os.path.isfile(stats_path):
        raise SystemExit(f"Expected both {model_path} and {stats_path}")

    env = None
    vec = None
    try:
        env = WalkEnv(init_noise=0.0, push_force=0.0)
        command = np.array([args.vx, args.vy, args.wz], dtype=np.float64)
        if np.any(command < env.cmd_lo) or np.any(command > env.cmd_hi):
            raise SystemExit(f"Command {command.tolist()} outside training limits {env.cmd_lo.tolist()} .. {env.cmd_hi.tolist()}")
        env.set_command(command)
        vec = VecNormalize.load(stats_path, DummyVecEnv([lambda: WalkEnv(init_noise=0.0)]))
        vec.training = False
        vec.norm_reward = False
        model = PPO.load(model_path, device="cpu")

        obs, _ = env.reset(seed=args.seed)
        step_count = int(np.ceil(args.seconds / env.control_dt))
        frames = []
        frame_durations_ms = []
        clipped_count = 0
        terminated = False

        for step in range(step_count):
            normalized = vec.normalize_obs(obs[np.newaxis, :])
            action, _ = model.predict(normalized, deterministic=True)
            obs, _, terminated, truncated, _ = env.step(action[0])
            is_sample = (step + 1) % args.stride == 0 or step + 1 == step_count
            if is_sample:
                # Convert MuJoCo target radians to offsets relative to WalkEnv.home_q.
                offset_deg = np.rad2deg(env.data.ctrl - env.home_q)
                clipped_count += int(np.count_nonzero(np.abs(offset_deg) > args.max_angle_deg))
                offset_deg = np.clip(offset_deg, -args.max_angle_deg, args.max_angle_deg)
                centidegrees = np.rint(offset_deg * 100).astype(np.int16)
                if centidegrees.shape != (19,):
                    raise SystemExit(f"Expected 19 humanoid joint targets, received {centidegrees.shape}")
                frames.append(centidegrees)
                steps_in_frame = min(args.stride, step_count - (len(frames) - 1) * args.stride)
                frame_durations_ms.append(int(round(env.control_dt * steps_in_frame * 1000)))
            if terminated or truncated:
                break

        if terminated:
            raise SystemExit("Simulation policy fell during export; no firmware file was written. Try a shorter duration or a better-trained model.")
        if not frames:
            raise SystemExit("No motion frames were sampled")
    finally:
        if env is not None:
            env.close()
        if vec is not None:
            vec.close()

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by RL/export_walk.py; do not edit by hand.\n")
        out.write("#pragma once\n#include <stdint.h>\n\n")
        out.write("static const uint8_t kMotionJointCount = 19;\n")
        out.write("struct MotionFrame { uint16_t durationMs; int16_t angleCdeg[kMotionJointCount]; };\n")
        out.write(f"static const uint16_t kMotionFrameCount = {len(frames)};\n")
        out.write("static const MotionFrame kMotionFrames[] PROGMEM = {\n")
        for frame, duration_ms in zip(frames, frame_durations_ms):
            values = ", ".join(str(int(value)) for value in frame)
            out.write(f"  {{{duration_ms}, {{{values}}}}},\n")
        out.write("};\n")

    print(f"Wrote {len(frames)} frames x 19 joints ({sum(frame_durations_ms)} ms total) to {args.output}")
    if clipped_count:
        print(f"Safety clamp applied to {clipped_count} joint samples at +/-{args.max_angle_deg:g} degrees")


if __name__ == "__main__":
    main()
